begin;

create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null check (char_length(btrim(full_name)) between 2 and 90),
  phone text check (phone is null or (char_length(phone) <= 24 and phone ~ '^[+]?[0-9() .-]{8,24})),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'client' check (role in ('admin','client','supervisee')),
  created_at timestamptz not null default now()
);
create table if not exists public.services (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9-]+$'),
  title text not null,
  summary text not null,
  active boolean not null default false,
  created_at timestamptz not null default now()
);

create or replace function public.set_profile_updated_at()
returns trigger language plpgsql security invoker set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;
drop trigger if exists trg_profiles_updated_at on public.profiles;
create trigger trg_profiles_updated_at
before update on public.profiles
for each row execute function public.set_profile_updated_at();

create or replace function public.handle_new_auth_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare
  clean_name text;
  clean_phone text;
begin
  clean_name := left(btrim(coalesce(new.raw_user_meta_data ->> 'full_name', '')), 90);
  if char_length(clean_name) < 2 then
    clean_name := 'Pessoa cadastrada';
  end if;
  clean_phone := nullif(left(btrim(coalesce(new.raw_user_meta_data ->> 'phone','')),24),'');
  if clean_phone is not null and clean_phone !~ '^\\+?[0-9() .-]{8,24}$' then
    clean_phone := null;
  end if;
  insert into public.profiles(user_id, full_name, phone)
  values(new.id, clean_name, clean_phone)
  on conflict (user_id) do nothing;
  insert into public.user_roles(user_id, role)
  values(new.id, 'client')
  on conflict (user_id) do nothing;
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users for each row execute function public.handle_new_auth_user();

alter table public.profiles enable row level security;
alter table public.user_roles enable row level security;
alter table public.services enable row level security;

-- A política de acesso não depende de propriedades alteráveis do usuário.
revoke all on table public.profiles from public, anon, authenticated;
revoke all on table public.user_roles from public, anon, authenticated;
revoke all on table public.services from public, anon, authenticated;

grant select on public.profiles to authenticated;
grant update(full_name, phone) on public.profiles to authenticated;
grant select on public.user_roles to authenticated;
grant select on public.services to anon, authenticated;

drop policy if exists profiles_self_select on public.profiles;
create policy profiles_self_select on public.profiles
for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists profiles_self_update on public.profiles;
create policy profiles_self_update on public.profiles
for update to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

drop policy if exists user_roles_self_select on public.user_roles;
create policy user_roles_self_select on public.user_roles
for select to authenticated using ((select auth.uid()) = user_id);
-- Sem políticas de escrita nem privilégios de INSERT/UPDATE/DELETE em papéis.
-- A promoção de administradora deve ser uma ação manual controlada do DBA.

drop policy if exists services_public_active on public.services;
create policy services_public_active on public.services
for select to anon, authenticated using (active = true);

insert into public.services (slug,title,summary,active) values
('psicologia-clinica','Psicologia Clínica','Apresentação informativa de acompanhamento psicológico.',true),
('psicologia-do-esporte','Psicologia do Esporte','Apresentação de atuação psicológica no contexto esportivo.',true),
('supervisao','Supervisão para Psicólogos','Apresentação de supervisão individual e em grupo.',true)
on conflict(slug) do nothing;

-- Usuários pré-existentes (caso o Supabase já tenha contas).
insert into public.profiles(user_id, full_name, phone)
select id,
  case when char_length(btrim(left(coalesce(raw_user_meta_data ->> 'full_name',''),90))) >= 2
    then btrim(left(raw_user_meta_data ->> 'full_name',90)) else 'Pessoa cadastrada' end,
  null
from auth.users on conflict (user_id) do nothing;
insert into public.user_roles(user_id,role)
select id,'client' from auth.users on conflict(user_id) do nothing;

commit;

